package part1;

// 1.5

public class Calculating {
  public static void main(String[] args) {
    int x = 5;
    System.out.println(x);
    int y = 10;
    System.out.println(y);

    int sum = x + y;
    System.out.println(sum);

    int sub = y - x;
    System.out.println(sub);

    int multi = x * y;
    System.out.println(multi);

    int result = y / x;
    System.out.println(result);
  }
}
